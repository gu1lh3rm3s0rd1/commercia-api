from datetime import datetime, timedelta, timezone
from decimal import Decimal
from typing import Literal
from uuid import UUID

from pydantic import AwareDatetime, BaseModel, ConfigDict, Field, field_validator

from app.models.enums import PaymentMethod
from app.modules.catalog.schemas import CategoryRead, DepartmentRead, Money, PriceRead, ProductRead, StockRead
from app.modules.sales.schemas import OrderItemCreate

CLOCK_TOLERANCE = timedelta(minutes=5)

# ---------------------------------------------------------------------
# push (mobile -> server): batch of sales made offline
# ---------------------------------------------------------------------


class SyncSaleCreate(BaseModel):
    """One offline sale from the mobile app's pending queue. client_reference is the
    idempotency key (generated by the app at sale time); occurred_at is required here
    (unlike the online OrderCreate) because a synced sale is meaningless without it —
    it's the whole reason this field exists.

    occurred_at must carry its UTC offset (e.g. 2026-11-07T10:00:00-03:00): a naive time
    would be read in whatever timezone the database session uses (UTC in production), which
    silently shifts the sale by hours in every report. It can't be in the future either
    (5 minutes of tolerance for device clocks). Unknown fields are rejected (422)."""

    model_config = ConfigDict(extra="forbid")

    client_reference: UUID
    client_id: int
    payment_method: PaymentMethod
    discount: Money = Decimal("0")
    occurred_at: AwareDatetime
    items: list[OrderItemCreate] = Field(min_length=1)

    @field_validator("occurred_at")
    @classmethod
    def _not_in_the_future(cls, value: datetime) -> datetime:
        if value > datetime.now(timezone.utc) + CLOCK_TOLERANCE:
            raise ValueError("occurred_at must not be in the future")
        return value


class PushRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    sales: list[SyncSaleCreate] = Field(min_length=1)


class PushResultItem(BaseModel):
    """created: new order. duplicate: this exact sale was already synced (order_id = the
    existing one). conflict: the client_reference is already used by a DIFFERENT sale (other
    content, or another filial) — nothing was written; the app has a bug to look at.
    rejected: business rule failed (stock, inactive client...), see reason."""

    client_reference: UUID
    status: Literal["created", "duplicate", "conflict", "rejected"]
    order_id: int | None = None
    reason: str | None = None


class PushResponse(BaseModel):
    results: list[PushResultItem]


# ---------------------------------------------------------------------
# pull (server -> mobile): catalog delta since last sync
# ---------------------------------------------------------------------


class SyncUserRead(BaseModel):
    """What the mobile app needs to log a user in offline: it runs bcrypt's checkpw on
    the typed password against password_hash (the salt lives inside the hash itself, so
    no extra field is needed). Inactive users are sent too so the app can block them."""

    model_config = {"from_attributes": True}

    id: int
    username: str
    password_hash: str
    is_active: bool
    is_superuser: bool


class PullResponse(BaseModel):
    synced_at: datetime
    departments: list[DepartmentRead]
    categories: list[CategoryRead]
    products: list[ProductRead]
    prices: list[PriceRead]
    stocks: list[StockRead]
    # Always the FULL list for the filial, ignoring last_synced_at: users has no
    # updated_at, and a user losing access to the filial is a deleted user_companies row,
    # which an incremental pull could never express. The app replaces its local table.
    users: list[SyncUserRead]
